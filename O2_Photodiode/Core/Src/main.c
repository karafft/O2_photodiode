void HAL_ADC_ConvCpltCallback(ADC_HandleTypeDef *hadc)
{
  uint16_t val = HAL_ADC_GetValue(hadc);

  switch (phase)
  {
  case 0:
    dark = val;
    if (led1_en)
      HAL_GPIO_WritePin(LED1_GPIO_Port, LED1_Pin, GPIO_PIN_RESET);
    phase = 1;
    break;

  case 1:
    led1_val = val;
    HAL_GPIO_WritePin(LED1_GPIO_Port, LED1_Pin, GPIO_PIN_SET);
    if (led2_en)
      HAL_GPIO_WritePin(LED2_GPIO_Port, LED2_Pin, GPIO_PIN_RESET);
    phase = 2;
    break;

  default:
    led2_val = val;
    HAL_GPIO_WritePin(LED2_GPIO_Port, LED2_Pin, GPIO_PIN_SET);
    sig1 = (int16_t)led1_val - (int16_t)dark;
    sig2 = (int16_t)led2_val - (int16_t)dark;
    frame_ready = 1;
    phase = 0;
    break;
  }
}

static void set_rate(uint32_t fps)
{
  if (fps < 10)
    fps = 10;
  if (fps > 200)
    fps = 200;

  __HAL_TIM_SET_AUTORELOAD(&htim2, TIM_TICK_HZ / (SLOTS * fps) - 1);
  __HAL_TIM_SET_COUNTER(&htim2, 0);
}

/* START | STOP | LED,<mask> | RATE,<fps> */
static void handle_cmd(const char *cmd)
{
  if (strcmp(cmd, "START") == 0)
  {
    streaming = 1;
  }
  else if (strcmp(cmd, "STOP") == 0)
  {
    streaming = 0;
  }
  else if (strncmp(cmd, "LED,", 4) == 0)
  {
    int mask = atoi(cmd + 4);
    led1_en = mask & 1;
    led2_en = (mask >> 1) & 1;
  }
  else if (strncmp(cmd, "RATE,", 5) == 0)
  {
    set_rate((uint32_t)atoi(cmd + 5));
  }
}

void HAL_UART_RxCpltCallback(UART_HandleTypeDef *huart)
{
  if (rx_byte == '\n' || rx_byte == '\r')
  {
    cmd_buf[cmd_len] = '\0';
    if (cmd_len > 0)
      handle_cmd(cmd_buf);
    cmd_len = 0;
  }
  else if (cmd_len < sizeof(cmd_buf) - 1)
  {
    cmd_buf[cmd_len++] = (char)rx_byte;
  }

  HAL_UART_Receive_IT(huart, &rx_byte, 1);
}

